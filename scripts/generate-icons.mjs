// Copies the Feather icons the app uses (https://feathericons.com, MIT) from
// the feather-icons package into src/components/icons.gen.ts, as plain data:
// only these icons end up in the app, not the whole set.
//
// To use another icon: add its name below (as on feathericons.com) and run
// `corepack pnpm icons`.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const NAMES = [
	"arrow-down",
	"arrow-up",
	"calendar",
	"check",
	"chevron-down",
	"clock",
	"copy",
	"download",
	"edit",
	"edit-2",
	"file-plus",
	"help-circle",
	"home",
	"info",
	"lock",
	"log-in",
	"log-out",
	"mail",
	"pen-tool",
	"play",
	"plus",
	"refresh-cw",
	"rotate-ccw",
	"save",
	"send",
	"square",
	"trash-2",
	"user",
	"user-check",
	"user-minus",
	"user-plus",
	"x",
	"x-circle",
];

const require = createRequire(import.meta.url);
const all = JSON.parse(
	readFileSync(require.resolve("feather-icons/dist/icons.json"), "utf8"),
);

/** '<line x1="1" y1="2"></line>' -> [["line", { x1: "1", y1: "2" }]] */
function parts(svg) {
	return [...svg.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(([, tag, attrs]) => [
		tag,
		Object.fromEntries(
			[...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]),
		),
	]);
}

const icons = Object.fromEntries(
	NAMES.map((name) => {
		if (!all[name]) throw new Error(`No Feather icon called "${name}".`);
		return [name, parts(all[name])];
	}),
);

const version = JSON.parse(
	readFileSync(require.resolve("feather-icons/package.json"), "utf8"),
).version;

writeFileSync(
	new URL("../src/components/icons.gen.ts", import.meta.url),
	`// Generated by scripts/generate-icons.mjs from feather-icons ${version}
// (https://feathericons.com, MIT licence, © Cole Bemis). Do not edit: add
// the icon's name to the script and run \`corepack pnpm icons\`.

export const ICONS = ${JSON.stringify(icons, null, "\t")} as const satisfies Record<
	string,
	readonly (readonly [string, Readonly<Record<string, string>>])[]
>;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`Wrote ${NAMES.length} icons.`);
