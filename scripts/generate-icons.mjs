/**
 * Icons Feather doesn't have, drawn in its style (24×24, 2px round strokes,
 * no fill) in the same form as the generated ones. Attribute names as SVG
 * spells them (text-anchor): they are passed on as they are, and the Redact
 * runtime doesn't rename textAnchor-style names. A part's text goes in
 * children.
 */
const CUSTOM = {
	// The Markdown mark (public domain): M and an arrow down, in a box.
	markdown: [
		["rect", { x: "2", y: "5", width: "20", height: "14", rx: "2", ry: "2" }],
		["path", { d: "M6 15V9l3 3 3-3v6" }],
		["line", { x1: "17", y1: "9", x2: "17", y2: "15" }],
		["polyline", { points: "14.5 12.5 17 15 19.5 12.5" }],
	],
	// A page with a folded corner and "PDF" on it.
	"file-pdf": [
		["path", { d: "M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z" }],
		["polyline", { points: "14 2 14 8 20 8" }],
		[
			"text",
			{
				x: "12",
				y: "18",
				"text-anchor": "middle",
				"font-size": "7",
				"font-weight": "800",
				"font-family": "system-ui, sans-serif",
				fill: "currentColor",
				stroke: "none",
				children: "PDF",
			},
		],
	],
};

const require = createRequire(import.meta.url);
const all = JSON.parse(
	readFileSync(require.resolve("feather-icons/dist/icons.json"), "utf8"),
);

/** '<line x1="1" y1="2"></line>' -> [["line", { x1: "1", y1: "2" }]] */
function parts(svg) {
	return [...svg.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(([, tag, attrs]) => [
		tag,
		Object.fromEntries(
			[...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]),
		),
	]);
}

const icons = {
	...Object.fromEntries(
		NAMES.map((name) => {
			if (!all[name]) throw new Error(`No Feather icon called "${name}".`);
			return [name, parts(all[name])];
		}),
	),
	...CUSTOM,
};

const version = JSON.parse(
	readFileSync(require.resolve("feather-icons/package.json"), "utf8"),
).version;

writeFileSync(
	new URL("../src/components/icons.gen.ts", import.meta.url),
	`// Generated by scripts/generate-icons.mjs from feather-icons ${version}
// (https://feathericons.com, MIT licence, © Cole Bemis), plus a few drawn in
// its style (markdown, file-pdf). Do not edit: add the icon to the script
// and run \`corepack pnpm icons\`.

export const ICONS = ${JSON.stringify(icons, null, "\t")} as const satisfies Record<
	string,
	readonly (readonly [string, Readonly<Record<string, string>>])[]
>;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`Wrote ${NAMES.length} icons.`);
